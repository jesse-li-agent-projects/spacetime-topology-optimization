"""Shared fixture loading and tolerance-policy helpers for MATLAB-vs-Python tests.

See `sttopt/conventions.md` for the array-order, fixture-format, and tolerance
conventions this module implements. Fixtures are `.mat` files generated by the MATLAB
harness (`tests/fixtures/generate_fixtures.m`) and committed under `tests/fixtures/`.
"""

from pathlib import Path

import numpy as np
import scipy.io

import sttopt.fem as fem

FIXTURES_DIR = Path(__file__).parent / "fixtures"


def fixture_element_perm(nelx: int, nely: int) -> np.ndarray:
    """Maps a `.mat` fixture's 0-indexed element numbering (F-order/column-major, the
    frozen MATLAB convention) to `sttopt`'s 0-indexed element numbering (C-order/
    row-major -- see `sttopt/conventions.md`). `perm[e_fixture] == e_sttopt`.
    """
    e = np.arange(nelx * nely)
    i, j = e // nely, e % nely  # F-order decode: i = x-index, j = y-index
    return j * nelx + i  # C-order encode


def fixture_node_perm(nelx: int, nely: int) -> np.ndarray:
    """`fixture_element_perm`, for the `(nely+1, nelx+1)` *node* grid rather than the
    element grid. `perm[n_fixture] == n_sttopt`.
    """
    n = np.arange((nelx + 1) * (nely + 1))
    c, r = n // (nely + 1), n % (nely + 1)  # F-order decode
    return fem.node_grid(nelx, nely)[r, c]


def fixture_dof_perm(nelx: int, nely: int) -> np.ndarray:
    """`fixture_node_perm`, lifted to dofs: each node `n` owns the interleaved `(x, y)`
    pair `2n`, `2n+1`, so a dof keeps its component and follows its node.
    """
    node_perm = fixture_node_perm(nelx, nely)
    return np.stack([2 * node_perm, 2 * node_perm + 1], axis=-1).ravel()


def node_positions(nelx: int, nely: int) -> tuple[np.ndarray, np.ndarray]:
    """Inverse of `fem.node_grid`: the `(row, col)` grid position of every node, as two
    arrays indexed by global node number. Lets a test that knows a node's mesh position
    state an expectation per dof without re-deriving the numbering formula.
    """
    nodes = fem.node_grid(nelx, nely)
    rows, cols = np.indices(nodes.shape)
    row_of = np.empty(nodes.size, int)
    col_of = np.empty(nodes.size, int)
    row_of[nodes.ravel()] = rows.ravel()
    col_of[nodes.ravel()] = cols.ravel()
    return row_of, col_of


def point_load_problem(nelx: int, nely: int) -> tuple[np.ndarray, np.ndarray, int]:
    """`(F, freedofs, ndof)` for the fixed cantilever load case the fixtures were
    generated under: unit downward point load on the bottom-right node, left edge
    clamped in both directions. This is the geometry MATLAB's `F(2*(nelx+1)*(nely+1))
    = -1` / `fixeddofs = 1:2*(nely+1)` denote; keeping it here rather than restating
    those formulas per test file keeps it in step with `optimize.build_problem`.
    """
    nodes = fem.node_grid(nelx, nely)
    ndof = 2 * nodes.size
    F = np.zeros(ndof)
    F[2 * nodes[-1, -1] + 1] = -1.0
    left_edge = nodes[:, 0]
    fixeddofs = np.stack([2 * left_edge, 2 * left_edge + 1], axis=-1).ravel()
    return F, np.setdiff1d(np.arange(ndof), fixeddofs), ndof


def reindex_fixture(arr: np.ndarray, nelx: int, nely: int, axis: int = 0) -> np.ndarray:
    """Reindexes a fixture-derived array's element axis (length `nelx*nely`) from the
    fixture's F-order to `sttopt`'s C-order (`fixture_element_perm`), leaving any other
    axes untouched. For a matrix indexed by element on *both* axes (e.g. a filter
    matrix), call this once per axis.
    """
    perm = fixture_element_perm(nelx, nely)
    out = np.empty_like(arr)
    out.swapaxes(0, axis)[perm] = arr.swapaxes(0, axis)
    return out


def reindex_fixture_nodes(
    arr: np.ndarray, nelx: int, nely: int, axis: int = 0
) -> np.ndarray:
    """`reindex_fixture`, for a node-indexed axis (length `(nelx+1)*(nely+1)`) rather
    than an element-indexed one.
    """
    perm = fixture_node_perm(nelx, nely)
    out = np.empty_like(arr)
    out.swapaxes(0, axis)[perm] = arr.swapaxes(0, axis)
    return out


def reindex_fixture_values(idx: np.ndarray, nelx: int, nely: int) -> np.ndarray:
    """Relabels a fixture-derived array of element *index values* (e.g. neighbor-pair
    `e1`/`e2` columns) from F-order to C-order -- as opposed to `reindex_fixture`,
    which reorders an array's element *axis* but leaves stored values unchanged.
    """
    return fixture_element_perm(nelx, nely)[idx]


def reindex_fixture_halves(
    arr: np.ndarray, nelx: int, nely: int, axis: int = 0
) -> np.ndarray:
    """`reindex_fixture`, for a raw-MMA-variable-shaped axis: `[x_half; t_half]`
    stacked along `axis`, each half element-indexed (length `nelx*nely`) and reindexed
    independently.
    """
    nel = nelx * nely
    swapped = arr.swapaxes(0, axis)
    x_half = reindex_fixture(swapped[:nel], nelx, nely, axis=0)
    t_half = reindex_fixture(swapped[nel:], nelx, nely, axis=0)
    return np.concatenate([x_half, t_half], axis=0).swapaxes(0, axis)


def load_fixture(name: str) -> dict:
    """Load a MATLAB-generated fixture by base filename (no `.mat` suffix).

    Returns a dict of numpy arrays as MATLAB saved them — 1-indexed element numbers
    where the source used 1-indexing (e.g. COO neighbor-list triplets), unconverted.
    Callers subtract 1 when comparing against Python's 0-indexed arrays.
    """
    return scipy.io.loadmat(
        FIXTURES_DIR / f"{name}.mat", squeeze_me=True, spmatrix=False
    )


def matlab_init_state(problem, beta_d: float):
    """The initial state the `.mat` fixtures were generated from: the reference's
    initialization, which leaves `xTilde` and `tPhys` unfiltered
    (`generate_fixtures.m:200-203`).

    `optimize.init_state` deliberately no longer reproduces this -- it derives both
    physics fields through the filter, since `step` differentiates `tPhys` as though
    `tPhys = H @ t / Hs` (PR #26). The committed `.mat` files are frozen artifacts of
    the old code and cannot be regenerated to match, so tests that compare against them
    enter the trajectory here instead, and keep checking what they were written to check
    -- the per-iteration agreement of `step`, not the seeding. `init_state`'s own
    behaviour is specified by `test_optimize.py`'s three init invariant tests.

    Unlike this helper, the live transliteration oracle (`matlab_reference_loop.py`)
    *does* follow the fix: it is code under our control, not a frozen artifact.
    """
    import sttopt.filters as filters
    import sttopt.optimize as optimize
    import sttopt.timefield as timefield

    x = np.full((problem.nely, problem.nelx), problem.volfrac)
    tPhys = timefield.init_timefield(problem.nelx, problem.nely, problem.tfield)
    nel = problem.nelx * problem.nely

    return optimize.State(
        x=x,
        xTilde=x.copy(),
        xPhys=filters.heaviside_projection(x.copy(), beta_d, problem.eta),
        t=tPhys.copy(),
        tPhys=tPhys,
        xold1=np.concatenate([x.flatten(), np.zeros(nel)]),
        xold2=np.concatenate([x.flatten(), np.zeros(nel)]),
        low=np.zeros(problem.n),
        upp=np.zeros(problem.n),
        loop=0,
        beta_t=10.0,
        beta_d=beta_d,
        factor=1.0,
    )


def load_fixture_npz(name: str) -> dict:
    """Load a Python-generated (non-MATLAB) fixture by base filename (no `.npz` suffix).

    For regression fixtures with no MATLAB counterpart -- e.g. golden values frozen from
    a Python scene the source MATLAB code never modeled -- 0-indexed throughout.
    """
    with np.load(FIXTURES_DIR / f"{name}.npz") as data:
        return dict(data)


def e2e_rtol(
    iteration: int, *, base_rtol: float = 1e-9, max_rtol: float = 1e-2
) -> float:
    """Relative tolerance for an end-to-end trajectory comparison at a given loop iteration.

    `subsolv`'s inner Newton line search amplifies small per-iteration differences, so
    exact agreement isn't realistic after many MMA iterations. Tolerance grows
    geometrically with iteration count (one decade looser per iteration by default),
    capped at `max_rtol`; tune `base_rtol`/`max_rtol` per test if this default doesn't
    match observed behavior.
    """
    return min(max_rtol, base_rtol * 10 ** (iteration - 1))


def assert_close(
    actual,
    expected,
    *,
    tier: str = "algebraic",
    iteration: int | None = None,
    atol: float = 1e-12,
):
    """Compare a ported quantity to its MATLAB fixture value, per the tolerance policy.

    tier:
      - "algebraic": purely algebraic, no linear solve involved (rtol=1e-10) — filters,
        neighbor weights, KE.
      - "solved": downstream of a sparse linear solve (rtol=1e-6) — U, compliance and
        its sensitivities.
      - "e2e": end-to-end trajectory comparison; pass `iteration` to scale tolerance
        via `e2e_rtol`.
    """
    tier_rtol = {"algebraic": 1e-10, "solved": 1e-6}
    if tier == "e2e":
        if iteration is None:
            raise ValueError("tier='e2e' requires `iteration`")
        rtol = e2e_rtol(iteration)
    else:
        rtol = tier_rtol[tier]
    np.testing.assert_allclose(
        np.asarray(actual), np.asarray(expected), rtol=rtol, atol=atol
    )
